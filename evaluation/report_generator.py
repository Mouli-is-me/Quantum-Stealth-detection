"""
Evaluation Report Generator Module
Produces formatted Markdown evaluation reports (evaluation_report.md) for technical presentation.
"""

from typing import Dict, Any


class EvaluationReportGenerator:
    """Generates structured Markdown evaluation reports summarizing AI performance, robustness, and benchmarks."""

    @staticmethod
    def generate_markdown_report(
        overall_metrics: Dict[str, Any],
        environmental_robustness: Dict[str, Any],
        failure_robustness: Dict[str, Any],
        fusion_benchmark: Dict[str, Any],
        failure_cases: list,
        report_path: str = "evaluation/evaluation_report.md"
    ) -> str:
        """
        Formats and saves a complete Markdown evaluation report.
        """
        total_samples = overall_metrics.get("total_samples", 0)
        acc = overall_metrics.get("accuracy", 0.0)
        prec = overall_metrics.get("precision", 0.0)
        rec = overall_metrics.get("recall", 0.0)
        f1 = overall_metrics.get("f1_score", 0.0)
        fa_rate = overall_metrics.get("false_alarm_rate", 0.0)
        miss_rate = overall_metrics.get("missed_detection_rate", 0.0)
        cal = overall_metrics.get("calibration", {})

        per_class = overall_metrics.get("per_class_metrics", {})

        report_lines = [
            "# AEGIS-X — AI Evaluation & Validation Report",
            "",
            "**Notice**: This evaluation is conducted using synthetic, physics-inspired simulation data generated by the AEGIS-X Scenario Engine.",
            "",
            "## 1. Executive Metrics Summary",
            "",
            f"- **Total Scenarios Evaluated**: {total_samples}",
            f"- **Overall Classification Accuracy**: **{acc * 100:.2f}%**",
            f"- **Precision**: {prec * 100:.2f}%",
            f"- **Recall (Detection Rate)**: {rec * 100:.2f}%",
            f"- **F1 Score**: {f1 * 100:.2f}%",
            f"- **False Alarm Rate**: {fa_rate * 100:.2f}%",
            f"- **Missed Detection Rate**: {miss_rate * 100:.2f}%",
            f"- **Expected Calibration Error (ECE)**: {cal.get('expected_calibration_error', 0.0):.4f}",
            "",
            "---",
            "",
            "## 2. Per-Class Accuracy Breakdown",
            "",
            "| Target Class | Evaluated Samples | Correct Predictions | Per-Class Accuracy |",
            "| :--- | :---: | :---: | :---: |"
        ]

        for c_name, c_data in per_class.items():
            c_tot = c_data.get("total", 0)
            c_cor = c_data.get("correct", 0)
            c_acc = c_data.get("accuracy", 0.0)
            report_lines.append(f"| **{c_name}** | {c_tot} | {c_cor} | **{c_acc * 100:.1f}%** |")

        report_lines.extend([
            "",
            "---",
            "",
            "## 3. Environmental & Weather Robustness",
            "",
            "| Environmental Condition | Classification Accuracy | Detection Rate | False Alarm Rate | Avg Confidence |",
            "| :--- | :---: | :---: | :---: | :---: |"
        ])

        for env_name, env_data in environmental_robustness.items():
            e_acc = env_data.get("accuracy", 0.0)
            e_dr = env_data.get("detection_rate", 0.0)
            e_fa = env_data.get("false_alarm_rate", 0.0)
            e_conf = env_data.get("avg_confidence", 0.0)
            report_lines.append(f"| **{env_name}** | {e_acc * 100:.1f}% | {e_dr * 100:.1f}% | {e_fa * 100:.1f}% | {e_conf:.2f} |")

        report_lines.extend([
            "",
            "---",
            "",
            "## 4. Hardware Failure & Degraded Sensor Robustness",
            "",
            "| Sensor Health State | Classification Accuracy | Detection Rate | False Alarm Rate | Avg Confidence |",
            "| :--- | :---: | :---: | :---: | :---: |"
        ])

        for health_name, health_data in failure_robustness.items():
            h_acc = health_data.get("accuracy", 0.0)
            h_dr = health_data.get("detection_rate", 0.0)
            h_fa = health_data.get("false_alarm_rate", 0.0)
            h_conf = health_data.get("avg_confidence", 0.0)
            report_lines.append(f"| **{health_name}** | {h_acc * 100:.1f}% | {h_dr * 100:.1f}% | {h_fa * 100:.1f}% | {h_conf:.2f} |")

        raw_b = fusion_benchmark.get("raw_baseline", {})
        fused_b = fusion_benchmark.get("adaptive_fusion", {})
        gains = fusion_benchmark.get("performance_improvement", {})

        report_lines.extend([
            "",
            "---",
            "",
            "## 5. Comparative Sensor Fusion Benchmark",
            "",
            "Quantitative evaluation comparing Raw Single-Sensor Baselines vs Adaptive Multi-Sensor Fusion:",
            "",
            "| Evaluation Mode | Accuracy | Precision | Recall (Detection Rate) | False Alarm Rate | F1 Score |",
            "| :--- | :---: | :---: | :---: | :---: | :---: |",
            f"| **Raw Unweighted Baseline** | {raw_b.get('accuracy', 0)*100:.1f}% | {raw_b.get('precision', 0)*100:.1f}% | {raw_b.get('recall', 0)*100:.1f}% | {raw_b.get('false_alarm_rate', 0)*100:.1f}% | {raw_b.get('f1_score', 0)*100:.1f}% |",
            f"| **Adaptive Multi-Sensor Fusion** | **{fused_b.get('accuracy', 0)*100:.1f}%** | **{fused_b.get('precision', 0)*100:.1f}%** | **{fused_b.get('recall', 0)*100:.1f}%** | **{fused_b.get('false_alarm_rate', 0)*100:.1f}%** | **{fused_b.get('f1_score', 0)*100:.1f}%** |",
            "",
            f"**Measured Impact**: Adaptive Sensor Fusion achieved **+{gains.get('accuracy_gain_pct', 0):.2f}% Accuracy Improvement** and **-{gains.get('false_alarm_reduction_pct', 0):.2f}% Reduction in False Alarms**.",
            "",
            "---",
            "",
            "## 6. Failure Case Diagnostics & Strategic Recommendations",
            "",
            f"Logged **{len(failure_cases)} Edge Case Failure(s)** during stress testing.",
            "",
            "### Recommendations for Tactical Deployment",
            "1. **Active ECM Environment Protocol**: Continue prioritizing passive Infrared and Thermal channels during heavy electronic jamming.",
            "2. **Precipitation Obscuration Thresholds**: Utilize optical visibility scaling under heavy rain to avoid visual camera false alarms.",
            "3. **Multi-Contact Discrimination**: Maintain radar micro-doppler integration for drone swarm vs biological clutter discrimination."
        ])

        report_content = "\n".join(report_lines)

        try:
            with open(report_path, "w", encoding="utf-8") as f:
                f.write(report_content)
        except Exception:
            pass

        return report_content
